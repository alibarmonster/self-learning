"""Writes src/exams/ace/questions/<section>.ts from the reviewed bank.

Inputs (in this folder): final-input.json (parse -> clean -> fixups) and
final.json (agent review -> adjudicate). Run: python3 build.py <repo>/src/exams/ace/questions
"""
import json, sys, os, collections
outdir = sys.argv[1]
inp = {q['n']: q for q in json.load(open('final-input.json'))}
rev = {o['n']: o for o in json.load(open('final.json'))}

def js(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n') + "'"

SECTIONS = {
    'setup': 'Setting up a cloud solution environment',
    'planning': 'Planning and configuring a cloud solution',
    'deploying': 'Deploying and implementing a cloud solution',
    'operating': 'Ensuring successful operation of a cloud solution',
    'access': 'Configuring access and security',
}
by = collections.defaultdict(list)
for n in sorted(rev):
    by[rev[n]['section']].append(n)

os.makedirs(outdir, exist_ok=True)
for sec, title in SECTIONS.items():
    out = ['/**',
           f' * Associate Cloud Engineer — {title}.',
           ' *',
           ' * Generated by scripts/importers/ace-pdf/build.py from a community question dump',
           ' * (667 questions; one exact duplicate dropped). `ace-NNN` is the question number in',
           ' * that PDF. Every key was reviewed against current Google Cloud documentation; where',
           ' * the dump\'s key was clearly wrong it was corrected, and the explanation opens with',
           ' * "The PDF\'s key says …". Questions are verbatim, so they skip the option-length check.',
           ' * The intermediate review data is not kept, so this file is now the source: edit it',
           ' * directly.',
           ' */',
           "import type { Question } from '@/types';",
           '',
           f'export const {sec}: Question[] = [']
    items = []
    for n in by[sec]:
        q, r = inp[n], rev[n]
        letters = q['letters']
        idx = [letters.index(c) for c in r['answer']]
        answer = str(idx[0]) if len(idx) == 1 else '[' + ', '.join(map(str, sorted(idx))) + ']'
        lines = ['  {',
                 f"    id: 'ace-{n:03d}',",
                 f"    topic: {js(r['topic'])},",
                 f"    difficulty: '{r['difficulty']}',",
                 '    verbatim: true,',
                 f"    prompt: {js(q['prompt'])},"]
        if q.get('code'):
            lines.append(f"    lang: {js(q.get('lang', ''))},")
            lines.append(f"    code: {js(q['code'])},")
        lines.append('    options: [')
        lines.append(',\n'.join(f'      {js(o)}' for o in q['options']))
        lines.append('    ],')
        lines.append(f'    answer: {answer},')
        lines.append(f"    explanation: {js(r['explanation'])}" + (',' if r.get('tip') else ''))
        if r.get('tip'):
            lines.append(f"    tip: {js(r['tip'])}")
        lines.append('  }')
        items.append('\n'.join(lines))
    out.append(',\n'.join(items))
    out.append('];')
    open(os.path.join(outdir, f'{sec}.ts'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(sec, len(by[sec]))
